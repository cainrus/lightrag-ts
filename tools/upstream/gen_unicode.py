"""Generate src/internal/py_unicode.ts: character classes as the rag-venv's CPython sees them.

Node's ICU ships a newer Unicode than CPython 3.12 (15.0), so `\\p{Nd}` and a
hand-written isdigit() would drift; the port uses these tables instead.

  ~/.claude-home/rag-venv/bin/python -I tools/upstream/gen_unicode.py > src/internal/py_unicode.ts
"""

import re
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cls(rs):
    esc = lambda cp: f"\\\\u{{{cp:x}}}"
    return "".join(esc(a) if a == b else f"{esc(a)}-{esc(b)}" for a, b in rs)


re_d = re.compile(r"\d")
re_s = re.compile(r"\s")
print(f"// GENERATED by tools/upstream/gen_unicode.py from CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.")
print("// Bodies of regex character classes; use with the `u` flag.")
print()
print("/** `str.isdigit()` */")
print(f"export const PY_ISDIGIT = '{cls(ranges(lambda c: c.isdigit()))}';")
print("/** `\\d` in a str pattern */")
print(f"export const PY_RE_DIGIT = '{cls(ranges(lambda c: re_d.match(c) is not None))}';")
print("/** `\\s` in a str pattern */")
print(f"export const PY_RE_SPACE = '{cls(ranges(lambda c: re_s.match(c) is not None))}';")
