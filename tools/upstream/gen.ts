// Generate src/prompt.ts and src/internal/html5_entities.ts from upstream.json
// (written by tools/upstream/dump.py). Values are emitted with JSON.stringify,
// so every template stays byte-identical to upstream prompt.py.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
type Upstream = {
  version: string;
  python: string;
  prompts: Record<string, string | string[]>;
  html5_entities: Record<string, string>;
  html_invalid_charrefs: Record<string, string>;
  html_invalid_codepoints: number[];
  constants: Record<string, unknown>;
};
const up = JSON.parse(readFileSync(`${root}tools/upstream/upstream.json`, 'utf8')) as Upstream;

const header = (what: string) =>
  `// GENERATED by tools/upstream/gen.ts from ${what} of lightrag-hku ${up.version}. Do not edit.\n`;

const promptLines = Object.keys(up.prompts)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(up.prompts[k])},`);
writeFileSync(
  `${root}src/prompt.ts`,
  header('lightrag/prompt.py') +
    `\nexport const PROMPTS_VERSION = ${JSON.stringify(up.version)};\n\n` +
    `export const PROMPTS = {\n${promptLines.join('\n')}\n} as const;\n\n` +
    `export type PromptKey = keyof typeof PROMPTS;\n`,
);

const constLines = Object.keys(up.constants)
  .sort()
  .map((k) => `export const ${k} = ${JSON.stringify(up.constants[k])};`);
writeFileSync(`${root}src/constants.ts`, header('lightrag/constants.py') + '\n' + constLines.join('\n') + '\n');

writeFileSync(
  `${root}src/internal/html5_entities.ts`,
  header(`CPython html module (${up.python.split(' ')[0]})`) +
    `\nexport const HTML5: Readonly<Record<string, string>> = ${JSON.stringify(up.html5_entities)};\n\n` +
    `export const INVALID_CHARREFS: Readonly<Record<string, string>> = ${JSON.stringify(up.html_invalid_charrefs)};\n\n` +
    `export const INVALID_CODEPOINTS: ReadonlySet<number> = new Set(${JSON.stringify(up.html_invalid_codepoints)});\n`,
);
console.log(`generated from lightrag ${up.version}: ${promptLines.length} prompts, ${constLines.length} constants`);
